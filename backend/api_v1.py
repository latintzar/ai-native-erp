KEY_PREFIX = "rk_live_"
PAGE_DEFAULT, PAGE_MAX = 50, 200


# ── errors ──────────────────────────────────────────────────────────────────────────────────────
def problem(status: int, kind: str, title: str, detail: str = "",
            headers: Optional[dict] = None) -> JSONResponse:
    """RFC 9457. One shape for every failure, so a client writes one error branch."""
    body = {"type": f"{PROBLEM_BASE}/{kind}", "title": title, "status": status}
    if detail:
        body["detail"] = detail
    return JSONResponse(body, status_code=status, headers=headers or {},
                        media_type="application/problem+json")


UNAUTH = dict(
    status=401, kind="credential-required",
    title="This endpoint needs an API key",
    detail=("Send a read-only key as `Authorization: Bearer rk_live_…`. The schema is public and "
            f"needs no key: {SPEC_URL}"),
)


# ── keys ────────────────────────────────────────────────────────────────────────────────────────
# Hashed at rest and prefix-identifiable, the same way the MCP tokens are. A key can be revoked
# NOW because it is a row; a signed token could not be recalled.


async def ensure_schema() -> None:
    """Verify migration ownership; application requests never alter schema."""
    from schema_migrations import assert_current

    async with db.get_pool().acquire() as connection:
        await assert_current(connection)


def _hash(raw: str) -> str:
    return hashlib.sha256(raw.encode()).hexdigest()


async def mint_key(tenant_id: str, label: str = "", created_by: str = "console") -> str:
    """Mint a key and return it ONCE — the plaintext is never stored and cannot be shown again.

    Called from the panel or the console, deliberately not over HTTP: handing out credentials is a
    much bigger thing to get right than checking them, and nothing published promises it.
    """
    raw = KEY_PREFIX + secrets.token_urlsafe(32)
    async with db._pool.acquire() as con:
        await con.execute(
            "insert into api_key (tenant_id, label, prefix, key_hash, created_by) "
            "values ($1,$2,$3,$4,$5)",
            tenant_id, label or None, raw[:len(KEY_PREFIX) + 6], _hash(raw), created_by)
    return raw


async def _tenant_for(request: Request) -> Optional[str]:
    """The tenant comes off the KEY, never off the request. No parameter can ask for another
    business's rows, which is the one property this surface cannot afford to get wrong."""
    auth = request.headers.get("authorization", "")
    if not auth.lower().startswith("bearer "):
        return None
    raw = auth[7:].strip()
    if not raw.startswith(KEY_PREFIX):
        return None
    # FAIL CLOSED, NEVER LOUD. A wrong-but-well-formed key reaches the database, so anything the
    # database does badly — pool not up yet, table not created, a transient — must still come out
    # of this function as «no tenant», which the caller turns into a 401. An evaluator poking the
    # API with junk credentials should never be able to make it answer 500: a 500 reads as a
    # broken product, and it is the one impression this surface exists to prevent.
    try:
        async with db._pool.acquire() as con:
            rec = await con.fetchrow(
                "select id, tenant_id from api_key where key_hash = $1 and revoked_at is null",
                _hash(raw))
            if rec is None:
                return None
            # a last-used stamp is what makes «my key doesn't work» self-serve on the Accesos strip
            await con.execute("update api_key set last_used_at = now() where id = $1", rec["id"])
        return rec["tenant_id"]
    except Exception:
        log.warning("v1 key lookup failed", exc_info=True)
        return None


# ── cursors ─────────────────────────────────────────────────────────────────────────────────────
# Opaque, and over (created_at, id) rather than an offset: offset skips rows while the day is
# still moving, and a distributor's day moves all morning.
def _encode(ts: Any, ident: Any) -> str:
    raw = f"{ts.isoformat() if hasattr(ts, 'isoformat') else ts}|{ident}"
    return base64.urlsafe_b64encode(raw.encode()).decode().rstrip("=")


def _decode(cursor: str) -> Optional[tuple[str, str]]:
    try:
        pad = "=" * (-len(cursor) % 4)
        ts, _, ident = base64.urlsafe_b64decode(cursor + pad).decode().partition("|")
        return ts, ident
    except Exception:
        return None


def _dt(v: str) -> datetime:
    """ISO 8601 text -> a real datetime, because asyncpg binds by INFERRED TYPE.

    A `$1::timestamptz` cast is applied by Postgres AFTER the driver has already encoded the
    parameter, and asyncpg — having inferred the column is a timestamptz — insists on a
    `datetime` and raises on a string. The cast in the SQL is not a conversion; it is a promise
    the driver checks. This is the whole of the bug that made every page after the first 503.
    """
    d = datetime.fromisoformat(v.replace("Z", "+00:00"))
    return d if d.tzinfo else d.replace(tzinfo=timezone.utc)


def _iso(v: Any) -> Any:
    return v.isoformat() if isinstance(v, datetime) else v


def _money(amount: Any, currency: str = "EUR") -> Optional[dict]:
    if amount is None:
        return None
    return {"amount": float(amount), "currency": currency}


def _page(rows: list[dict], limit: int, ts_key: str, id_key: str = "id") -> dict:
    nxt = None
    if len(rows) > limit:
        rows = rows[:limit]
        last = rows[-1]
        nxt = _encode(last.get("_ts"), last.get("_id"))
    for r in rows:
        r.pop("_ts", None)
        r.pop("_id", None)
    return {"data": rows, "next_cursor": nxt}


async def _fetch(table: str, tenant: str, ts_col: str, id_col: str,
                 since: Optional[str], cursor: Optional[str], limit: int,
                 extra_where: str = "", extra_args: Optional[list] = None) -> list[dict]:
    """One paging query, shared by every resource — so `since`, the cursor and the ordering
    cannot behave differently on one endpoint than on another."""
    args: list[Any] = [tenant]
    where = ["tenant_id = $1"]
    if extra_where:
        where.append(extra_where)
        args.extend(extra_args or [])
    if since:
        args.append(_dt(since))
        where.append(f"{ts_col} >= ${len(args)}")
    if cursor:
        dec = _decode(cursor)
        if dec is None:
            raise ValueError("cursor")
        args.extend([_dt(dec[0]), dec[1]])
        a, b = len(args) - 1, len(args)
        # Spelled out rather than as a row constructor `(ts, id) < ($1, $2)`, whose parameter types
        # the driver could not infer.
        where.append(f"({ts_col} < ${a} or ({ts_col} = ${a} and {id_col}::text < ${b}))")
    args.append(limit + 1)
    sql = (f"select * from {table} where {' and '.join(where)} "
           f"order by {ts_col} desc, {id_col} desc limit ${len(args)}")
    async with db._pool.acquire() as con:
        recs = await con.fetch(sql, *args)
    return [dict(r) for r in recs]


def _limit(v: int) -> int:
    return max(1, min(int(v or PAGE_DEFAULT), PAGE_MAX))


