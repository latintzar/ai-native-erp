"""THE PUBLIC READ API — `/v1/*`, the surface soyrocoto.com/docs describes.

WHY IT EXISTS, in Peter's words (2026-08-09): «not like they'd be able to get any data without a
key, but they can still check it to get the schema or whatever the fuck is the typical thing».

That is the whole design brief and it is a good one. An IT lead evaluating a vendor does not start
by asking for credentials — he curls the base URL and reads the spec. Before this file, every path
in the documentation answered `404`, and a 404 says *there is no API here*. With it, the same curl
answers `401` with a problem document and a `WWW-Authenticate` header, which says *there is an API
here and you need a key* — and `/v1/openapi.json` hands over the whole schema with no key at all.
The difference between those two replies is the difference between a document and a product.

WHAT IS DELIBERATELY IN
  · every path the docs name, all of them real
  · `rk_live_…` keys, hashed at rest, prefix-identifiable, revocable, per-tenant
  · cursor pagination over (created_at, id) — never offset, because offset skips rows while the
    day is still moving and a distributor's day moves all morning
  · `?since=` as the poller's contract
  · RFC 9457 `application/problem+json` on every error
  · read-only, always: there is no write verb on this surface by design (§17.54c). Writes go
    through the panel or MCP, where every change is a draft a person accepts.

WHAT IS DELIBERATELY OUT
  · key MINTING over HTTP. A key is minted in the panel or from the console with `mint_key()`;
    an endpoint that hands out credentials is a much bigger thing to get right than one that
    checks them, and nothing in the documentation promises it.
  · anything that writes.

THE SPEC IS NOT DUPLICATED HERE. `/v1/openapi.json` redirects to the one the site publishes, which
is generated by `landing/docs.py`. Two hand-kept copies of a schema is precisely how the old
developer docs drifted, and a redirect costs a generator one hop.
"""
