async def _listing(request: Request, name: str, since: Optional[str],
                   cursor: Optional[str], limit: int):
    tenant = await _tenant_for(request)
    if tenant is None:
        return problem(**UNAUTH, headers={"WWW-Authenticate": 'Bearer realm="Rocoto API"'})
    table, ts_col, id_col, shape = RESOURCES[name]
    n = _limit(limit)
    if cursor and _decode(cursor) is None:
        return problem(422, "bad-cursor", "That cursor could not be read",
                       "Use the `next_cursor` from the previous page, unchanged.")
    if since:
        try:
            datetime.fromisoformat(since.replace("Z", "+00:00"))
        except Exception:
            return problem(422, "bad-since", "`since` must be ISO 8601",
                           "For example: 2026-08-01T00:00:00%2B02:00")
    try:
        rows = await _fetch(table, tenant, ts_col, id_col, since, cursor, n)
    except Exception:
        log.exception("v1 %s query failed", name)
        return problem(503, "temporarily-unavailable", "This resource could not be read just now",
                       "The request was well formed. Try again, and tell us if it persists.")
    return _page([shape(r) for r in rows], n, ts_col, id_col)


def _mount(name: str) -> None:
    async def handler(request: Request,
                      since: Optional[str] = Query(None),
                      cursor: Optional[str] = Query(None),
                      limit: int = Query(PAGE_DEFAULT, ge=1, le=PAGE_MAX),
                      _n: str = name):
        return await _listing(request, _n, since, cursor, limit)

    handler.__name__ = f"v1_list_{name}"
    router.add_api_route(f"/{name}", handler, methods=["GET"],
                         summary=f"List {name} since your high-water mark")


for _name in RESOURCES:
    _mount(_name)


@router.get("/orders/{order_id}", summary="One order, with its lines")
async def get_order(request: Request, order_id: str):
    tenant = await _tenant_for(request)
    if tenant is None:
        return problem(**UNAUTH, headers={"WWW-Authenticate": 'Bearer realm="Rocoto API"'})
    rec = await db.order_get(order_id, tenant=tenant)
    if not rec:
        # 404 for an id in ANOTHER tenant too: existence is never leaked across businesses
        return problem(404, "not-found", "No order with that id",
                       "Ids are per-business and opaque.")
    out = _order(rec)
    out.pop("_ts", None)
    out.pop("_id", None)
    return out


@router.get("/documents", summary="Delivery notes and filed documents")
async def documents(request: Request):
    """Named in the published spec, and its store is still the panel's own. Rather than answer with
    an empty page — which reads as «you have no documents» and is a different lie from «not yet» —
    it says what it is."""
    tenant = await _tenant_for(request)
    if tenant is None:
        return problem(**UNAUTH, headers={"WWW-Authenticate": 'Bearer realm="Rocoto API"'})
    return problem(503, "opening-with-your-pilot", "This resource opens with your pilot",
                   "Documents are served from the panel today. Everything else under /v1 answers now.")
