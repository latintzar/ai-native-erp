#!/usr/bin/env python3
"""The backend's map, generated from the backend. Paths resolve from the script, so it runs anywhere.

`backend/` is 178 modules and 87,562 lines. A map a person keeps by hand goes stale the week it is
written — the one this replaced named a file that had been deleted and missed the whole of `brain/`.
So the table is read out of the source every time, and `--check` makes a stale table a red run.

  python3 tools/backend-map.py            rewrite backend/ARCHITECTURE.md
  python3 tools/backend-map.py --check    exit 1 when the file on disk differs from the source

What each column says:

  module    the path under backend/
  layer     kernel · app · untagged, read from backend/tests/vital_kernel_boundary.py's KERNEL and
            APP sets — the layering law itself, never a second copy of it. The sets hold IMPORT
            names, so `brain/*.py` reads its tag from `brain`. A module in neither set is untagged.
  lines     the file's line count
  what      the first line of the module docstring, or «—» when it carries none

Everything after the tables is written by hand and lives in tools/backend-map-prose.md — «How it
hangs together», and whatever else the backend's own sections need. The generator pastes that file
in whole, so regenerating the tables keeps it.

The date in the header is the date the map last CHANGED. When the regenerated body matches the file
on disk, the old date is kept — a map that still describes the backend correctly is not stale
because a day passed, and `--check` would otherwise turn red every midnight.
"""
from __future__ import annotations

import argparse
import ast
import datetime as dt
import difflib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT / "backend"
LAW = BACKEND / "tests" / "vital_kernel_boundary.py"
PROSE = ROOT / "tools" / "backend-map-prose.md"
MAP = BACKEND / "ARCHITECTURE.md"
STAMP = re.compile(r"^_Generated by .* on (\d{4}-\d{2}-\d{2}) .*_$", re.M)
PURPOSE_MAX = 116

# One table per package, in this order. Anything else lands in the table for its own directory,
# after these, so a new package appears in the map the day it appears in the tree.
PACKAGES = ["root", "brain"]
TITLES = {"root": "`backend/` — the modules at the top level", "brain": "`backend/brain/` — the domain layer"}


def law_sets() -> tuple[frozenset[str], frozenset[str]]:
    """KERNEL and APP, read out of the vital that enforces them. One source of truth for the tag."""
    tree = ast.parse(LAW.read_text(encoding="utf-8"))
    found: dict[str, frozenset[str]] = {}
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        for target in node.targets:
            if isinstance(target, ast.Name) and target.id in ("KERNEL", "APP"):
                found[target.id] = frozenset(ast.literal_eval(node.value))
    missing = {"KERNEL", "APP"} - set(found)
    if missing:
        raise SystemExit(f"backend-map: {LAW.relative_to(ROOT)} no longer defines {', '.join(sorted(missing))}")
    return found["KERNEL"], found["APP"]


def modules() -> list[Path]:
    """Every python file under backend/, outside the test tree, sorted by path."""
    tests = BACKEND / "tests"
    return sorted(
        p for p in BACKEND.rglob("*.py")
        if tests not in p.parents and p != tests
    )


def import_name(path: Path) -> str:
    """The name the layering law would see: the package for a module inside one, else the stem."""
    rel = path.relative_to(BACKEND)
    return rel.parts[0] if len(rel.parts) > 1 else rel.stem


def package(path: Path) -> str:
    rel = path.relative_to(BACKEND)
    return "root" if len(rel.parts) == 1 else rel.parts[0]


def purpose(text: str, path: Path) -> str:
    """The first line of the module docstring, one table cell wide."""
    try:
        doc = ast.get_docstring(ast.parse(text))
    except SyntaxError as e:
        return f"(unparsed: line {e.lineno})"
    if not doc:
        return "—"
    line = " ".join(doc.strip().splitlines()[0].split())
    if len(line) > PURPOSE_MAX:
        line = line[: PURPOSE_MAX - 1].rstrip() + "…"
    return line.replace("|", "\\|")


def rows() -> list[dict]:
    kernel, app = law_sets()
    out = []
    for path in modules():
        text = path.read_text(encoding="utf-8", errors="replace")
        name = import_name(path)
        out.append({
            "path": str(path.relative_to(BACKEND)),
            "package": package(path),
            "lines": len(text.splitlines()),
            "layer": "kernel" if name in kernel else "app" if name in app else "untagged",
            "purpose": purpose(text, path),
        })
    return out


def prose() -> str:
    if not PROSE.exists():
        raise SystemExit(f"backend-map: the hand-written section is missing at {PROSE.relative_to(ROOT)}")
    return PROSE.read_text(encoding="utf-8").strip()


def body(data: list[dict]) -> str:
    """Everything under the stamp line: the legend, one table per package, then the prose."""
    parts = [
        "The tag in the `layer` column is the layering law of "
        "[`tests/vital_kernel_boundary.py`](tests/vital_kernel_boundary.py): the KERNEL is the generic",
        "employee nervous system (versioned in `KERNEL-VERSION`, surface in `KERNEL-API.md`), the APP is",
        "Rocoto's commerce world built on it. A kernel module importing an app module is the breach the",
        "vital fails on. The sets hold import names, so every module under `brain/` reads the tag of",
        "`brain`. **untagged** means the law names the module nowhere yet — that is the work the map",
        "makes visible, and each one belongs on one side.",
        "",
        "Regenerate with `python3 tools/backend-map.py`. CI runs `--check`; an edit here alone goes back.",
    ]
    order = PACKAGES + sorted({r["package"] for r in data} - set(PACKAGES))
    for name in order:
        group = [r for r in data if r["package"] == name]
        if not group:
            continue
        title = TITLES.get(name, f"`backend/{name}/`")
        parts += [
            "",
            f"## {title}",
            "",
            f"{len(group)} modules · {sum(r['lines'] for r in group):,} lines · "
            + " · ".join(
                f"{sum(1 for r in group if r['layer'] == layer)} {layer}"
                for layer in ("kernel", "app", "untagged")
            ),
            "",
            "| module | layer | lines | what it is |",
            "|---|---|--:|---|",
        ]
        for r in group:
            parts.append(f"| `{r['path']}` | {r['layer']} | {r['lines']:,} | {r['purpose']} |")
    parts += ["", prose(), ""]
    return "\n".join(parts)


def render(previous: str = "") -> str:
    data = rows()
    new_body = body(data)
    old = STAMP.search(previous)
    # The body is everything after the stamp line; the title above it is not part of the body.
    old_body = previous[old.end():].strip() if old else ""
    date = old.group(1) if old and old_body == new_body.strip() else dt.date.today().isoformat()
    counts = " · ".join(
        f"{sum(1 for r in data if r['layer'] == layer)} {layer}" for layer in ("kernel", "app", "untagged")
    )
    stamp = (
        f"_Generated by `tools/backend-map.py` on {date} · {len(data)} modules · "
        f"{sum(r['lines'] for r in data):,} lines · {counts}._"
    )
    return f"# Rocoto backend — the module map\n\n{stamp}\n\n{new_body}"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 when backend/ARCHITECTURE.md is stale")
    args = ap.parse_args()

    current = MAP.read_text(encoding="utf-8") if MAP.exists() else ""
    fresh = render(current)

    if not args.check:
        MAP.write_text(fresh, encoding="utf-8")
        print(f"backend-map: wrote {MAP.relative_to(ROOT)} · {fresh.splitlines()[2]}")
        return 0

    # The check reads the map's substance, never the date: a map that still describes the backend is
    # current on any day. (Before this, the title line leaked into the body compare, so the gate went
    # red at midnight on an untouched repository.)
    undated = lambda text: STAMP.sub("_Generated by `tools/backend-map.py`_", text, count=1)
    if undated(current) == undated(fresh):
        print(f"backend-map: GREEN · {MAP.relative_to(ROOT)} matches the source")
        return 0

    diff = list(difflib.unified_diff(
        current.splitlines(), fresh.splitlines(),
        fromfile=f"a/{MAP.relative_to(ROOT)}", tofile="the source", lineterm="", n=0,
    ))
    added = sum(1 for line in diff if line.startswith("+") and not line.startswith("+++"))
    removed = sum(1 for line in diff if line.startswith("-") and not line.startswith("---"))
    for line in diff[:40]:
        print(line)
    if len(diff) > 40:
        print(f"… {len(diff) - 40} more diff lines")
    print(f"backend-map: RED · {MAP.relative_to(ROOT)} is stale by {added} line(s) added, "
          f"{removed} removed. Run `python3 tools/backend-map.py`.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
