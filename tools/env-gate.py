#!/usr/bin/env python3
"""The environment contract: every name the services read is in .env.example, and nothing else is.

Paths resolve from the script, so it runs from anywhere.

  python3 tools/env-gate.py            check both directions; exit 1 on either miss
  python3 tools/env-gate.py --write    rewrite .env.example from the source

An unset name is a default, and a default is a decision nobody made. `.env.example` named ten
variables while `backend/config.py` alone read about a hundred and ninety, so the names that matter
most — the runtime DSN whose absence bypasses row-level security, the webhook secrets, the owner
allowlist — were invisible to anyone standing up a box. This gate makes the file the contract:

  * a name a service reads and the file omits is a door nobody knew to close
  * a name in the file nothing reads is a promise nobody can keep

How a name is found (pure AST, no import):

  os.getenv(NAME) · os.environ.get(NAME) · os.environ[NAME]
  the config helpers — _env · _bool · _int · _float · _lower_set — reached as `config._env(NAME)`,
  or bare inside the module that defines them (which is how each config.py reads its own)
  any function that passes an argument of its own to one of those, so a wrapper counts too
  (`mock-api/app/config.py:_first_env("GOOGLE_PLACES_API_KEY", "GOOGLE_MAPS_API_KEY")` is two reads)

A name held in a variable is resolved through that module's string constants, so
`_KEY_ENV = "ROCOTO_SECRET_KEY"` in `backend/channels.py` counts as a read of ROCOTO_SECRET_KEY.

The file is grouped by subsystem, and the group titles are the config files' own comments — the
drawn section rules and the comment blocks between them. A name read outside a config file is
grouped under the module that reads it. A name with a default in the source carries it as a
comment, and a name production must carry is marked. Comments sit on their OWN line: the
repository's .env readers (`backend/narrate.py:_load_env_file`) split a line on the first `=` and
keep everything after it, so a trailing comment would become part of the value.
"""
from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXAMPLE = ROOT / ".env.example"
DEMO_EXAMPLE = ROOT / "deploy/staging/demo.env.example"
# These deployment paths belong to the unit, rather than to provider configuration.
DEMO_UNIT_NAMES = {"ROCOTO_RUNTIME_STATE_DIR", "ROCOTO_RUNTIME_PUBLIC_BASE"}

# The two python services this repository runs. `.env.example` is the repository's file, so the
# gate's second direction — a name nothing reads — is only true if it looks at both.
TREES = ("backend", "mock-api")
SKIP_DIR_NAMES = {"tests", "node_modules", "__pycache__"}
CONFIG_FILES = ("backend/config.py", "mock-api/app/config.py")

HELPERS = {"_env", "_bool", "_int", "_float", "_lower_set"}
ENVISH = re.compile(r"[A-Z][A-Z0-9_]{1,}")
SECTION = re.compile(r"^\s*#\s*─{2,}\s*(.*?)\s*─*\s*$")
ASSIGN = re.compile(r"^([A-Z][A-Z0-9_]*)=")            # a line of .env.example
SECRETISH = re.compile(r"SECRET|TOKEN|PASSWORD|_KEY\b|API_KEY|CREDENTIAL")
DEFAULT_MAX = 72
TITLE_MAX = 96

# Production must carry these, and each one's absence is permissive rather than loud: the four DSNs
# and switches (an unset DATABASE_URL points at a local database, an unset RUNTIME_DATABASE_URL
# leaves the owner role bypassing FORCE RLS, an unset IS_PROD keeps every dev fallback open), the
# API key, the channel-secret key, the owner allowlist, and the four webhook secrets. Source: the
# review of 2026-09-06. `config.assert_prod_ready()` names the boot's own list once it exists; this
# gate marks the union of the two, so the marker can only grow.
REVIEWED_REQUIRED = frozenset({
    "DATABASE_URL", "RUNTIME_DATABASE_URL", "CONTROL_DATABASE_URL", "IS_PROD", "ROCOTO_API_KEY",
    "ROCOTO_SECRET_KEY", "OWNER_EMAILS", "FB_APP_SECRET", "WA_CLOUD_VERIFY_TOKEN",
    "TWILIO_AUTH_TOKEN", "ELEVENLABS_WEBHOOK_SECRET", "STRIPE_WEBHOOK_SECRET",
})

# Those names lead the file in one group of their own. They are scattered through config.py, and
# several sit under a section comment about something else — IS_PROD under the Medusa block,
# TWILIO_AUTH_TOKEN under Supabase auth — so inheriting the nearest header would file them under
# the wrong subject. This is the group a person standing up a box reads first.
FIRST_GROUP = "The names production must carry — the databases, the keys, the webhook secrets"

HEADER = """\
# The environment contract. Copy to .env.local (gitignored); values come from the accounts named in
# docs/THE-CONNECTIONS-SPEC.md and the register in docs/THE-VENDOR-REGISTER.md.
#
# Generated by `tools/env-gate.py --write` from every name {trees} read. The same script
# without a flag is the gate: a name the code reads and this file omits is a red run, and so is a
# name here that nothing reads. Add the name here in the same pull request as the code that reads it.
#
# `# REQUIRED IN PRODUCTION` marks a name whose absence is permissive rather than loud.
# `# default:` is what the source falls back to when the name is unset.
# Comments are on their own line on purpose: the readers in this repository split a line on its
# first `=` and keep everything after it, so a trailing comment would become part of the value.
#
# {count} names · {required} of them required in production.
"""


def python_files(tree: str) -> list[Path]:
    base = ROOT / tree
    return sorted(
        p for p in base.rglob("*.py")
        if not (SKIP_DIR_NAMES & set(p.relative_to(base).parts[:-1]))
    )


def readers(tree: ast.Module) -> dict[str, bool]:
    """Functions in this module that read the environment for their caller, and whether each takes
    `*args` (so every argument is a name rather than only the first).

    Two kinds. The helpers a config.py defines over os.environ — a module with its own `_int(v)`
    that never touches the environment (`backend/brain/pedidos_usage_report.py`) is left alone. And
    any function that hands a value of its own to one of those: `_first_env(*names)` reads each of
    its arguments, so a call to it is a read of each. Found to a fixed point, so a wrapper of a
    wrapper counts."""
    functions = [n for n in ast.walk(tree) if isinstance(n, ast.FunctionDef)]
    out: dict[str, bool] = {}
    for node in functions:
        if node.name in HELPERS:
            dump = ast.dump(node)
            if "environ" in dump or "getenv" in dump:
                out[node.name] = node.args.vararg is not None
    for _ in range(4):
        grew = False
        for node in functions:
            if node.name in out:
                continue
            for call in ast.walk(node):
                if not isinstance(call, ast.Call):
                    continue
                is_read, args = env_read(call, out)
                # The name comes from the caller when it is anything but a literal in this body.
                if is_read and args and not literals(args[0], {}):
                    out[node.name] = node.args.vararg is not None
                    grew = True
                    break
        if not grew:
            break
    return out


def string_constants(tree: ast.Module) -> dict[str, set[str]]:
    """Every module- or function-level `NAME = "STRING"`, so a key held in a variable resolves."""
    out: dict[str, set[str]] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name):
                    out.setdefault(target.id, set()).update(literals(node.value, {}))
    return out


def literals(node: ast.AST, consts: dict[str, set[str]]) -> set[str]:
    """Every string this expression can be: a constant, either arm of a conditional, a name."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return {node.value}
    if isinstance(node, ast.Name):
        return set(consts.get(node.id, ()))
    if isinstance(node, ast.IfExp):
        return literals(node.body, consts) | literals(node.orelse, consts)
    if isinstance(node, ast.BoolOp):
        return set().union(*(literals(v, consts) for v in node.values))
    return set()


def default_of(node: ast.Call) -> str | None:
    """The fallback the source uses when the name is unset, as a comment-safe string."""
    if len(node.args) < 2:
        return None
    arg = node.args[1]
    if isinstance(arg, ast.UnaryOp) and isinstance(arg.op, ast.USub) and isinstance(arg.operand, ast.Constant):
        return f"-{arg.operand.value}"
    if not isinstance(arg, ast.Constant):
        return None
    value = arg.value
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, str):
        return value or None
    return None


def env_read(node: ast.Call, own: dict[str, bool]) -> tuple[bool, list[ast.AST]]:
    """Is this call an environment read, and which arguments hold names? The first argument always;
    every argument when the reader takes `*args`, because then each one is a name it may read."""
    f = node.func
    name = f.attr if isinstance(f, ast.Attribute) else f.id if isinstance(f, ast.Name) else None
    if name is None:
        return False, []
    if isinstance(f, ast.Attribute):
        hit = name == "getenv" or name in HELPERS
        if not hit and name == "get":
            base = f.value
            hit = (
                (isinstance(base, ast.Attribute) and base.attr == "environ")
                or (isinstance(base, ast.Name) and base.id == "environ")
            )
    else:
        hit = name == "getenv" or name in own
    if not hit:
        return False, []
    if own.get(name) and name not in HELPERS:
        return True, list(node.args)
    return True, node.args[:1]


def module_reads(path: Path) -> list[tuple[int, str, str | None]]:
    """Every environment read in one file: (line, name, the default at that line)."""
    try:
        module = ast.parse(path.read_text(encoding="utf-8", errors="replace"))
    except SyntaxError:
        print(f"env-gate: {path.relative_to(ROOT)} does not parse; its names are unread here")
        return []
    own = readers(module)
    consts = string_constants(module)
    out: list[tuple[int, str, str | None]] = []
    for node in ast.walk(module):
        if isinstance(node, ast.Call):
            is_read, args = env_read(node, own)
            for position, arg in enumerate(args):
                for name in literals(arg, consts):
                    if ENVISH.fullmatch(name):
                        out.append((node.lineno, name, default_of(node) if position == 0 else None))
        elif isinstance(node, ast.Subscript):
            base = node.value
            if isinstance(base, ast.Attribute) and base.attr == "environ":
                for name in literals(node.slice, consts):
                    if ENVISH.fullmatch(name):
                        out.append((node.lineno, name, None))
    return sorted(out)


def scan() -> dict[str, dict]:
    """Every environment name the two trees read, with where it is read and its default."""
    found: dict[str, dict] = {}
    for tree in TREES:
        for path in python_files(tree):
            for _, name, default in module_reads(path):
                entry = found.setdefault(name, {"files": set(), "default": None})
                entry["files"].add(str(path.relative_to(ROOT)))
                if entry["default"] is None and default is not None:
                    entry["default"] = default
    return found


def headings(path: Path, rel: str) -> list[tuple[int, str]]:
    """Where each subsystem starts in a config file, and what that file calls it.

    Two shapes count, both of them the file's own comments: a drawn section rule
    (`# ──── Owner / RBAC ────`), and the first line of a comment block that opens after a blank
    line (`# ElevenLabs Conversational AI — per-call voice autoreply…`). The second matters because
    config.py rules off some subsystems and only comments others: without it every ElevenLabs and
    Twilio name inherits the Supabase rule sixty lines above and reads as Supabase's."""
    found = [(0, f"`{rel}` — the head of the file")]
    blank = True
    previous_was_comment = False
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        stripped = line.strip()
        section = SECTION.match(line)
        if section and section.group(1):
            found.append((number, section.group(1)))
        elif stripped.startswith("#") and blank and not previous_was_comment:
            title = trim(stripped.lstrip("# ").strip())
            if title and not title.startswith("noqa"):
                found.append((number, title))
        previous_was_comment = stripped.startswith("#")
        blank = not stripped
    return found


def trim(title: str) -> str:
    """One line, one thought: the comment's first sentence, and never past the column."""
    stop = title.find(". ")
    if 30 <= stop < TITLE_MAX:
        return title[: stop + 1]
    return title[: TITLE_MAX - 1] + "…" if len(title) > TITLE_MAX else title


def groups() -> tuple[dict[str, str], list[str]]:
    """Each name's subsystem, read from the comments of the config files, plus the order those
    files put the subsystems in. The subsystem is found by LINE, so a constant whose python name
    differs from the environment name (`BRAND_NAME = _env("ROCOTO_BRAND_NAME", …)`) still lands in
    its own."""
    title_of: dict[str, str] = {}
    order: list[str] = []
    for rel in CONFIG_FILES:
        path = ROOT / rel
        if not path.exists():
            continue
        headers = headings(path, rel)
        used = set()
        for lineno, name, _ in module_reads(path):
            if name in title_of:
                continue
            title = next(t for line, t in reversed(headers) if line <= lineno)
            title_of[name] = title
            used.add(title)
        order += [t for _, t in headers if t in used and t not in order]
    return title_of, order


def required_names() -> frozenset[str]:
    """The reviewed list, plus every name the boot's own refusal reads.

    `backend/config.py` keeps that refusal in two constants and the functions around them:
    `_PROD_REQUIRED` is a tuple of names always needed, `_PROD_REQUIRED_WITH` a tuple of
    `(rail, its secret)` pairs where only the SECOND is required — the rail itself is optional, and
    marking it would tell an operator to set a Twilio account they may not have."""
    names = set(REVIEWED_REQUIRED)
    config = ROOT / "backend" / "config.py"
    if not config.exists():
        return frozenset(names)
    try:
        module = ast.parse(config.read_text(encoding="utf-8"))
    except SyntaxError:
        return frozenset(names)

    def envish(value) -> bool:
        return isinstance(value, str) and bool(ENVISH.fullmatch(value))

    for node in ast.walk(module):
        if isinstance(node, ast.Assign) and isinstance(node.value, (ast.Tuple, ast.List)):
            targets = [t.id for t in node.targets if isinstance(t, ast.Name)]
            if not any("PROD_REQUIRED" in name for name in targets):
                continue
            for element in node.value.elts:
                if isinstance(element, (ast.Tuple, ast.List)):   # (rail, its secret)
                    pair = [e.value for e in element.elts if isinstance(e, ast.Constant)]
                    if len(pair) == 2 and envish(pair[1]):
                        names.add(pair[1])
                elif isinstance(element, ast.Constant) and envish(element.value):
                    names.add(element.value)
        elif isinstance(node, ast.FunctionDef) and node.name in ("assert_prod_ready", "missing_prod_secrets"):
            for inner in ast.walk(node):
                if isinstance(inner, ast.Constant) and envish(inner.value):
                    names.add(inner.value)
    return frozenset(names)


def example_entries() -> tuple[list[str], dict[str, str]]:
    """The names .env.example declares, in order, and any value it already carries."""
    if not EXAMPLE.exists():
        return [], {}
    names, values = [], {}
    for line in EXAMPLE.read_text(encoding="utf-8").splitlines():
        match = ASSIGN.match(line)
        if match:
            name = match.group(1)
            names.append(name)
            value = line.split("=", 1)[1].strip()
            if value:
                values[name] = value
    return names, values


def render(found: dict[str, dict]) -> str:
    title_of, order = groups()
    required = required_names()
    _, kept = example_entries()

    buckets: dict[str, list[str]] = {}
    for name in sorted(found):
        if name in required:
            title = FIRST_GROUP
        else:
            title = title_of.get(name) or f"`{sorted(found[name]['files'])[0]}`"
        buckets.setdefault(title, []).append(name)

    ordered = [t for t in order if t in buckets] + sorted(t for t in buckets if t not in order)
    titles = ([FIRST_GROUP] if FIRST_GROUP in buckets else []) + [t for t in ordered if t != FIRST_GROUP]
    lines = [HEADER.format(
        trees=" and ".join(f"`{t}/`" for t in TREES),
        count=len(found),
        required=len(required & set(found)),
    ).rstrip()]
    for title in titles:
        lines += ["", f"# ── {title} ──"]
        for name in buckets[title]:
            notes = []
            if name in required:
                notes.append("REQUIRED IN PRODUCTION")
            default = found[name]["default"]
            if default and not SECRETISH.search(name):
                if len(default) > DEFAULT_MAX:
                    default = default[: DEFAULT_MAX - 1] + "…"
                notes.append(f"default: {default}")
            if notes:
                lines.append("# " + " · ".join(notes))
            lines.append(f"{name}={kept.get(name, '')}")
    return "\n".join(lines) + "\n"


def demo_names(found: dict[str, dict]) -> set[str]:
    """Only the demo application's readers; deployment helpers are separate processes."""
    return {name for name, entry in found.items()
            if any(path.startswith("mock-api/app/") for path in entry["files"])} - DEMO_UNIT_NAMES


def render_demo(names: set[str]) -> str:
    return (
        "# Demo kit runtime configuration; installed as /srv/rocoto/demo.env.\n"
        "# Generated by tools/env-gate.py --write from mock-api/app/ readers.\n"
        "# Fill dedicated sandbox values; unset names remain commented.\n"
        "# The systemd unit owns ROCOTO_RUNTIME_STATE_DIR and ROCOTO_RUNTIME_PUBLIC_BASE.\n"
        + "".join(f"# {name}=\n" for name in sorted(names))
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write", action="store_true", help="rewrite .env.example from the source")
    args = ap.parse_args()

    found = scan()
    declared, _ = example_entries()
    demo = render_demo(demo_names(found))

    if args.write:
        EXAMPLE.write_text(render(found), encoding="utf-8")
        DEMO_EXAMPLE.write_text(demo, encoding="utf-8")
        print(f"env-gate: wrote .env.example · {len(found)} names")
        print(f"env-gate: wrote deploy/staging/demo.env.example · {len(demo_names(found))} names")
        return 0

    read_only = sorted(set(found) - set(declared))
    declared_only = sorted(set(declared) - set(found))
    for name in read_only:
        where = sorted(found[name]["files"])
        print(f"  MISSING  {name} — read in {where[0]}"
              + (f" and {len(where) - 1} more" if len(where) > 1 else ""))
    for name in declared_only:
        print(f"  UNREAD   {name} — declared in .env.example, read nowhere in "
              + " or ".join(f"{t}/" for t in TREES))

    demo_drift = not DEMO_EXAMPLE.exists() or DEMO_EXAMPLE.read_text() != demo
    if demo_drift:
        print("  DEMO    deploy/staging/demo.env.example differs from mock-api/app/ readers")
    if read_only or declared_only or demo_drift:
        print(f"env-gate: RED · {len(read_only)} name(s) read and undeclared, "
              f"{len(declared_only)} declared and unread. Run `python3 tools/env-gate.py --write`.")
        return 1
    print(f"env-gate: GREEN · {len(found)} names, each read by the code and declared in .env.example")
    return 0


if __name__ == "__main__":
    sys.exit(main())
