#!/usr/bin/env python3
"""Generate source navigation statically, without importing application/provider code."""
from __future__ import annotations

import argparse
import ast
import json
import os
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docs/reference/source-index.md"


def python_module(path):
    tree = ast.parse(path.read_text())
    symbols = []
    def visit(node, scope=()):
        next_scope = scope
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            symbols.append({"name": ".".join((*scope, node.name)), "kind": type(node).__name__, "line": node.lineno})
            next_scope = (*scope, node.name)
        for child in ast.iter_child_nodes(node):
            visit(child, next_scope)
    visit(tree)
    summary = (ast.get_docstring(tree) or "").splitlines()
    return {"path": str(path.relative_to(ROOT)), "language": "Python",
            "summary": summary[0][:160] if summary else "", "symbols": symbols}


def generate():
    modules = []
    for directory in ("backend", "mock-api/app", "app/src/prototypes/copper/runtime"):
        for path in sorted((ROOT / directory).rglob("*.py")):
            if "__pycache__" not in path.parts and "tests" not in path.parts:
                modules.append(python_module(path))
    ts_files = []
    for directory in ("app/src/prototypes/cedar", "app/src/rocoto", "app/src/kit", "app/src/scenarios"):
        ts_files.extend(str(path.relative_to(ROOT)) for path in (ROOT / directory).rglob("*")
                        if path.suffix in {".ts", ".tsx"} and not path.name.endswith(".d.ts"))
    result = subprocess.run(["node", str(ROOT / "tools/source-reference.mjs"), *sorted(ts_files)], cwd=ROOT,
                            text=True, capture_output=True, check=True)
    modules.extend(json.loads(result.stdout))
    modules.sort(key=lambda item: item["path"])
    count = sum(len(module["symbols"]) for module in modules)
    lines = ["# Source reference", "", "Generated statically by `make source-reference`. Application modules and providers are not executed.", "",
             "The [kernel API](../../backend/KERNEL-API.md) identifies the public backend seam. The full navigation below includes internal implementation symbols and design components; it is not an SDK stability promise.", "",
             f"{len(modules)} modules; {count} named functions, classes, methods and TypeScript types. Anonymous callbacks are reached through their containing source. Literal defaults and private values are excluded.", ""]
    documents = {}
    current_group = None
    for module in modules:
        path = module["path"]
        if path.startswith("backend/"): group = "Maintained backend"
        elif path.startswith("mock-api/"): group = "Prototype APIs"
        elif path.startswith("app/src/prototypes/copper/"): group = "Native collection service"
        elif path.startswith("app/src/prototypes/cedar/"): group = "Cedar workspace"
        elif path.startswith("app/src/rocoto/"): group = "Shared components"
        elif path.startswith("app/src/scenarios/"): group = "Scenarios"
        else: group = "Component gallery"
        if group != current_group:
            lines.extend([f"## {group}", "", "| Module | Symbols | Source |", "|---|---:|---|"])
            current_group = group
        page = TARGET.parent / "modules" / (path + ".md")
        index_link = os.path.relpath(page, TARGET.parent)
        source_link = os.path.relpath(ROOT / path, page.parent)
        back_link = os.path.relpath(TARGET, page.parent)
        lines.append(f"| [{path}]({index_link}) | {len(module['symbols'])} | [code](../../{path}) |")
        page_lines = ["<!-- generated by tools/source-reference.py -->", f"# {path}", "",
                      f"[All modules]({back_link}) · [Source]({source_link})", ""]
        if module["summary"]:
            page_lines.extend([module["summary"].replace("<", "&lt;").replace(">", "&gt;"), ""])
        if module["symbols"]:
            page_lines.extend(["| Symbol | Kind | Source |", "|---|---|---|"])
            for symbol in module["symbols"]:
                name = symbol["name"].replace("|", "\\|")
                page_lines.append(f"| `{name}` | {symbol['kind']} | [L{symbol['line']}]({source_link}#L{symbol['line']}) |")
            page_lines.append("")
        documents[page] = "\n".join(page_lines)
    documents[TARGET] = "\n".join(lines) + "\n"
    documents[TARGET.parent / "symbols.json"] = json.dumps({"modules": modules}, indent=2) + "\n"
    return documents, len(modules), count


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    documents, modules, symbols = generate()
    if arguments.check:
        if any(not path.exists() or path.read_text() != content for path, content in documents.items()):
            raise SystemExit("Source navigation is stale; run make source-reference.")
    else:
        for path, content in documents.items():
            path.parent.mkdir(parents=True, exist_ok=True); path.write_text(content)
        for path in (TARGET.parent / "modules").rglob("*.md"):
            if path not in documents and path.read_text().startswith("<!-- generated by tools/source-reference.py -->"):
                path.unlink()
    print(json.dumps({"modules": modules, "symbols": symbols, "checked": arguments.check}))


if __name__ == "__main__":
    main()
